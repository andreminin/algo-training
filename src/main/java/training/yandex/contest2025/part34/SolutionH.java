package training.yandex.contest2025.part34;

import java.io.*;
import java.util.Arrays;

public class SolutionH {
    /*
       На столе лежит кучка из NN спичек. Двое играют в такую игру. За один ход разрешается взять из кучки одну, две или
       три спички, так чтобы оставшееся количество спичек не было простым числом (например, можно оставить в кучке
       1 или 4 спички, но нельзя оставить 2 или 3). Выигрывает тот, кто забирает последнюю спичку. Требуется определить, кто из игроков имеет выигрышную стратегию.
        Формат ввода

        Вводится одно число NN ( 1≤N≤100001≤N≤10000).
        Формат вывода

        Выведите число 1, если при правильной игре победит первый игрок (который делает первый ход), или число 2, если при правильной стратегии победит второй игрок.

        Пример 1
        Ввод
        Вывод
        1
        1

        Пример 2
        Ввод
        Вывод
        2
        1

        Предварительные вычисления: С помощью решета Эратосфена определяем все простые числа до N.

        Динамическое программирование: Массив dp хранит состояния выигрыша (true - выигрышная позиция, false - проигрышная).

        Базовый случай: dp[0] = false (нет спичек - проигрыш).

        Для каждого количества спичек от 1 до N проверяем все возможные ходы (взять 1, 2 или 3 спички). Ход valid, если оставшееся количество не является простым числом.

        Если существует ход, ведущий в проигрышную позицию для противника, текущая позиция выигрышная.

        Простые числа: Используем решето Эратосфена для отметки всех простых чисел до N.

        Динамическое программирование: Для каждого i от 1 до N проверяем, можно ли сделать ход (1, 2 или 3 спички),
        чтобы оставшееся количество не было простым и при этом перевести игру в проигрышную позицию для противника.

        Результат: Если dp[N] истинно, первый игрок выигрывает (выводим 1), иначе выигрывает второй (выводим 2).
     */

    public static void main(String[] args) throws IOException {
        try (BufferedReader reader = new BufferedReader(new InputStreamReader(System.in));
             BufferedWriter writer = new BufferedWriter(new OutputStreamWriter(System.out))) {

            int n = Integer.parseInt(reader.readLine());

            boolean[] prime = new boolean[n + 1];
            Arrays.fill(prime, true);

            prime[0] = false;
            prime[1] = false;
            for (int i = 2; i * i <= n; i++) {
                if (prime[i]) {
                    for (int j = i * i; j <= n; j += i) {
                        prime[j] = false;
                    }
                }
            }

            boolean[] dp = new boolean[n + 1];
            dp[0] = false;

            for (int i = 1; i <= n; i++) {
                dp[i] = false;
                for (int j = 1; j <= 3; j++) {
                    if (i - j >= 0 && !prime[i - j]) {
                        if (!dp[i - j]) {
                            dp[i] = true;
                            break;
                        }
                    }
                }
            }

            writer.write(dp[n] ? "1" : "2");
        }
    }
}
